//! Проверка листа против корня эпохи
//!
//! SHA-256, и это единственное отступление от проектного SHA-512/256: в Solana
//! syscall есть только на sha256, keccak и blake3, а SHA-512 программа считала
//! бы софтом и сжирала тысячи compute units на каждый уровень при лимите 200k

use solana_program::hash::hashv;
use solana_program::pubkey::Pubkey;

/// Теги разводят листья и узлы: без них лист выдаётся за узел, и умник подсунет
/// себе выплату, которой в дереве нихуя не было.
///
/// Значения ровно те же, что в payout.LeafHash башки: разъехавшийся на байт
/// формат означает корень, который не подтвердит ни один клейм
const LEAF: [u8; 1] = [0x00];
const NODE: [u8; 1] = [0x01];

/// Лист: номер в дереве, кому, сколько и за какую эпоху.
///
/// Номер эпохи внутри обязателен, иначе одну выплату предъявляют в каждой
/// следующей эпохе и доят казну. Индекс - чтобы отметка о выплате была битом в
/// эпохе, а не отдельным аккаунтом за ренту на каждого донора
pub fn leaf(index: u32, wallet: &Pubkey, amount: u64, epoch: u64) -> [u8; 32] {
    hashv(&[
        &LEAF,
        &index.to_le_bytes(),
        wallet.as_ref(),
        &amount.to_le_bytes(),
        &epoch.to_le_bytes(),
    ])
    .to_bytes()
}

/// Идём от листа к корню. Пара сортируется, чтобы дереву не требовалось
/// хранить направление шага
pub fn verify(root: &[u8; 32], mut node: [u8; 32], proof: &[[u8; 32]]) -> bool {
    for step in proof {
        node = if node <= *step {
            hashv(&[&NODE, &node, step]).to_bytes()
        } else {
            hashv(&[&NODE, step, &node]).to_bytes()
        };
    }
    node == *root
}
